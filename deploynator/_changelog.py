from __future__ import annotations

import os
import subprocess
from collections import defaultdict

from deploynator._config import Config
from deploynator._models import ChangelogEntry, CommitMessage, CommitType


class ChangelogGenerator:
    def __init__(self, config: Config) -> None:
        self._config = config

    def generate_from_log(
        self,
        repo_path: str,
        from_ref: str,
        to_ref: str = "HEAD",
    ) -> str:
        entries = self._collect_entries(repo_path, from_ref, to_ref)
        return self._format_entries(entries)

    def generate_from_messages(self, messages: list[str]) -> str:
        entries = []
        for msg in messages:
            try:
                parsed = CommitMessage.parse(msg)
                entries.append(
                    ChangelogEntry(
                        commit_type=parsed.commit_type,
                        message=msg,
                    )
                )
            except ValueError:
                entries.append(
                    ChangelogEntry(
                        commit_type=CommitType.CHORE,
                        message=msg,
                    )
                )
        return self._format_entries(entries)

    def generate_header(self) -> str:
        return f"{self._config.changelog_header}\n\n"

    def _collect_entries(self, repo_path: str, from_ref: str, to_ref: str) -> list[ChangelogEntry]:
        entries = []
        try:
            result = subprocess.run(
                ["git", "-C", repo_path, "log", f"{from_ref}..{to_ref}",
                 "--pretty=format:%s|||%an|||%h"],
                capture_output=True, text=True, check=False,
            )
            if result.returncode == 0 and result.stdout.strip():
                for line in result.stdout.strip().split("\n"):
                    parts = line.split("|||")
                    msg = parts[0] if len(parts) > 0 else ""
                    author = parts[1] if len(parts) > 1 else ""
                    sha = parts[2] if len(parts) > 2 else ""
                    if msg:
                        entry = ChangelogEntry.from_git_log_line(msg, author, sha)
                        entries.append(entry)
        except (subprocess.SubprocessError, FileNotFoundError):
            pass
        return entries

    def _format_entries(self, entries: list[ChangelogEntry]) -> str:
        if not entries:
            return f"{self._config.changelog_header}\n\nNo changes recorded.\n"

        sections: dict[str, list[ChangelogEntry]] = defaultdict(list)
        for entry in entries:
            header = entry.commit_type.section_header()
            sections[header].append(entry)

        header_order = [
            "Features", "Bug Fixes", "Hotfixes", "Code Refactoring",
            "Documentation", "Style Changes", "Chores", "Tests",
            "Releases", "Patches",
        ]

        lines = [self._config.changelog_header, ""]
        for section_name in header_order:
            section_entries = sections.get(section_name, [])
            if not section_entries:
                continue
            lines.append(f"### {section_name}")
            lines.append("")
            for entry in section_entries:
                sha_suffix = f" ({entry.sha})" if entry.sha else ""
                author_suffix = f" by {entry.author}" if entry.author else ""
                lines.append(f"  * {entry.message}{sha_suffix}{author_suffix}")
            lines.append("")

        lines.append(f"\n_Generated by [deploynator]({self._config.deploynator_badge_url})_")
        return "\n".join(lines)

    def write_changelog(self, repo_path: str, content: str, filename: str | None = None) -> str:
        target = filename or self._config.changelog_file
        full_path = os.path.join(repo_path, target)
        if os.path.islink(full_path):
            raise OSError(f"Symlink rejected: {full_path}")
        with open(full_path, "w") as f:
            f.write(content)
        return full_path

    def format_for_release(self, changelog_content: str, max_chars: int | None = None) -> str:
        limit = max_chars or self._config.max_release_chars
        if len(changelog_content) <= limit:
            return changelog_content
        truncated = changelog_content[:limit]
        truncated += "\n\n... _(truncated due to platform limits. See full CHANGELOG.md in repo.)_"
        return truncated
